use rust_xlsxwriter::{Color, Format, FormatAlign, FormatBorder, Workbook};

use crate::error::{AppError, AppResult};

use super::build::ReportSource;
use super::model::DocumentKind;

pub fn render_xlsx(kind: DocumentKind, source: &ReportSource<'_>) -> AppResult<Vec<u8>> {
    if !kind.supports_xlsx() {
        return Err(AppError::Validation(
            "XLSX export is only available for the test case tracker and findings register.".into(),
        ));
    }

    let mut workbook = Workbook::new();
    let title = format!("{} - {}", kind.label(), source.engagement.name);
    let worksheet = workbook.add_worksheet();
    worksheet
        .set_name(kind.label())
        .map_err(|error| AppError::Internal(format!("XLSX generation failed: {error}")))?;

    let title_format = Format::new()
        .set_bold()
        .set_font_size(14)
        .set_font_color(Color::RGB(0xF8FAFC))
        .set_background_color(Color::RGB(0x0F172A))
        .set_align(FormatAlign::Left);
    let meta_format = Format::new().set_font_color(Color::RGB(0x475569));
    let header_format = Format::new()
        .set_bold()
        .set_font_color(Color::RGB(0xF8FAFC))
        .set_background_color(Color::RGB(0x334155))
        .set_border(FormatBorder::Thin)
        .set_border_color(Color::RGB(0x475569))
        .set_align(FormatAlign::Left)
        .set_text_wrap();
    let cell_format = Format::new()
        .set_border(FormatBorder::Thin)
        .set_border_color(Color::RGB(0xE2E8F0))
        .set_align(FormatAlign::Top)
        .set_text_wrap();

    let (headers, rows, widths): (Vec<&str>, Vec<Vec<String>>, Vec<u16>) = match kind {
        DocumentKind::TestCaseTracker => (
            vec![
                "Test", "Category", "Status", "Result", "Assignee", "Approach", "Notes",
            ],
            source
                .test_cases
                .iter()
                .map(|test_case| {
                    vec![
                        test_case.title.clone(),
                        test_case.category.clone(),
                        status_label(test_case.status),
                        test_case.result.clone(),
                        test_case.assignee.clone(),
                        test_case.approach.clone(),
                        test_case.notes.clone(),
                    ]
                })
                .collect(),
            vec![45, 20, 14, 40, 18, 50, 40],
        ),
        DocumentKind::FindingsRegister => (
            vec![
                "Code",
                "Title",
                "Severity",
                "Status",
                "Retest",
                "Owner",
                "OWASP",
                "CWE",
                "Probability",
                "Impact",
                "Remediation",
                "Description",
            ],
            source
                .findings
                .iter()
                .map(|finding| {
                    vec![
                        finding.code.clone(),
                        finding.title.clone(),
                        severity_label(finding.severity),
                        finding_status_label(finding.status),
                        retest_label(finding.retest_status),
                        finding.owner.clone(),
                        finding.owasp.clone(),
                        finding.cwe.clone(),
                        finding.probability.to_string(),
                        finding.impact_score.to_string(),
                        finding.remediation.clone(),
                        finding.description.clone(),
                    ]
                })
                .collect(),
            vec![10, 40, 13, 14, 14, 16, 24, 16, 12, 10, 50, 60],
        ),
        _ => unreachable!(),
    };

    let last_col = (headers.len() - 1) as u16;
    worksheet
        .merge_range(0, 0, 0, last_col, &title, &title_format)
        .map_err(xlsx_error)?;
    worksheet.set_row_height(0, 24).map_err(xlsx_error)?;
    worksheet
        .write_string_with_format(
            1,
            0,
            format!(
                "Client code: {}",
                if source.engagement.client_code.is_empty() {
                    "Not recorded"
                } else {
                    &source.engagement.client_code
                }
            ),
            &meta_format,
        )
        .map_err(xlsx_error)?;
    worksheet
        .write_string_with_format(
            2,
            0,
            format!(
                "Generated by {} at {}",
                source.generated_by, source.generated_at
            ),
            &meta_format,
        )
        .map_err(xlsx_error)?;

    let header_row = 4;
    for (col, header) in headers.iter().enumerate() {
        worksheet
            .write_string_with_format(header_row, col as u16, *header, &header_format)
            .map_err(xlsx_error)?;
    }
    for (row_index, row) in rows.iter().enumerate() {
        for (col_index, value) in row.iter().enumerate() {
            worksheet
                .write_string_with_format(
                    header_row + 1 + row_index as u32,
                    col_index as u16,
                    value,
                    &cell_format,
                )
                .map_err(xlsx_error)?;
        }
    }
    for (index, width) in widths.iter().enumerate() {
        worksheet
            .set_column_width(index as u16, *width)
            .map_err(xlsx_error)?;
    }
    worksheet
        .set_freeze_panes(header_row + 1, 0)
        .map_err(xlsx_error)?;

    workbook
        .save_to_buffer()
        .map_err(|error| AppError::Internal(format!("XLSX generation failed: {error}")))
}

fn xlsx_error(error: rust_xlsxwriter::XlsxError) -> AppError {
    AppError::Internal(format!("XLSX generation failed: {error}"))
}

fn status_label(status: crate::domain::enums::TestCaseStatus) -> String {
    match status {
        crate::domain::enums::TestCaseStatus::NotStarted => "Not started".into(),
        crate::domain::enums::TestCaseStatus::InProgress => "In progress".into(),
        crate::domain::enums::TestCaseStatus::Done => "Done".into(),
        crate::domain::enums::TestCaseStatus::Blocked => "Blocked".into(),
        crate::domain::enums::TestCaseStatus::NotApplicable => "Not applicable".into(),
    }
}

fn severity_label(severity: crate::domain::enums::Severity) -> String {
    match severity {
        crate::domain::enums::Severity::Informational => "Informational".into(),
        crate::domain::enums::Severity::Low => "Low".into(),
        crate::domain::enums::Severity::Medium => "Medium".into(),
        crate::domain::enums::Severity::High => "High".into(),
        crate::domain::enums::Severity::Critical => "Critical".into(),
    }
}

fn finding_status_label(status: crate::domain::enums::FindingStatus) -> String {
    match status {
        crate::domain::enums::FindingStatus::Open => "Open".into(),
        crate::domain::enums::FindingStatus::InReview => "In review".into(),
        crate::domain::enums::FindingStatus::Remediated => "Remediated".into(),
        crate::domain::enums::FindingStatus::RetestPending => "Retest pending".into(),
        crate::domain::enums::FindingStatus::Closed => "Closed".into(),
        crate::domain::enums::FindingStatus::Accepted => "Accepted".into(),
    }
}

fn retest_label(status: crate::domain::enums::RetestStatus) -> String {
    match status {
        crate::domain::enums::RetestStatus::NotRequired => "Not required".into(),
        crate::domain::enums::RetestStatus::Pending => "Pending".into(),
        crate::domain::enums::RetestStatus::Passed => "Passed".into(),
        crate::domain::enums::RetestStatus::Failed => "Failed".into(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::documents::build::ReportSource;
    use crate::domain::enums::{EngagementStatus, TestCaseStatus};
    use crate::domain::models::{
        Assumption, Contact, Engagement, Evidence, Finding, Risk, ScopeAsset, TestCase,
    };

    #[test]
    fn renders_xlsx_zip() {
        let engagement = Engagement {
            id: "e1".into(),
            name: "Synthetic".into(),
            client_code: "SYN".into(),
            status: EngagementStatus::Active,
            start_date: "2026-01-01".into(),
            end_date: "2026-01-02".into(),
            application_summary: String::new(),
            attack_surface: String::new(),
            created_by: "p1".into(),
            created_at: "2026-01-01T00:00:00Z".into(),
            updated_at: "2026-01-01T00:00:00Z".into(),
            version: 1,
        };
        let test_cases = vec![TestCase {
            id: "t1".into(),
            engagement_id: "e1".into(),
            template_id: None,
            title: "Test".into(),
            approach: "Approach".into(),
            category: "Category".into(),
            status: TestCaseStatus::Done,
            result: "Result".into(),
            notes: String::new(),
            assignee: "Tester".into(),
            sort_order: 0,
            created_at: "2026-01-01T00:00:00Z".into(),
            updated_at: "2026-01-01T00:00:00Z".into(),
        }];
        let source = ReportSource {
            engagement: &engagement,
            scope_assets: &[] as &[ScopeAsset],
            risks: &[] as &[Risk],
            assumptions: &[] as &[Assumption],
            contacts: &[] as &[Contact],
            test_cases: &test_cases,
            findings: &[] as &[Finding],
            evidence: &[] as &[Evidence],
            generated_by: "Tester",
            generated_at: "2026-01-01T00:00:00Z",
        };
        let xlsx = render_xlsx(DocumentKind::TestCaseTracker, &source).expect("xlsx");
        assert!(xlsx.starts_with(b"PK"));
        assert!(xlsx.len() > 1000);
    }
}
