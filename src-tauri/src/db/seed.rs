pub fn seed_templates(conn: &Connection) -> AppResult<()> {
    let mut stmt = conn.prepare(
        "INSERT INTO test_case_templates (id, domain, category, title, approach, expected_result, references_text, source)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, 'builtin')
         ON CONFLICT(id) DO UPDATE SET
            domain = excluded.domain,
            category = excluded.category,
            title = excluded.title,
            approach = excluded.approach,
            expected_result = excluded.expected_result,
            references_text = excluded.references_text
         WHERE test_case_templates.source = 'builtin'",
    )?;
    for template in TEMPLATES {
        stmt.execute(rusqlite::params![
            template.id,
            template.domain,
            template.category,
            template.title,
            template.approach,
            template.expected,
            template.references,
        ])?;
    }
    drop(stmt);

    let now = chrono::Utc::now().to_rfc3339();
    for bundle in BUNDLES {
        conn.execute(
            "INSERT INTO test_template_bundles
                (id, name, description, version, source, origin_id, created_at, updated_at)
             VALUES (?1, ?2, ?3, ?4, 'builtin', NULL, ?5, ?5)
             ON CONFLICT(id) DO UPDATE SET
                name = excluded.name,
                description = excluded.description,
                version = excluded.version,
                updated_at = excluded.updated_at
             WHERE test_template_bundles.source = 'builtin'",
            rusqlite::params![
                bundle.id,
                bundle.name,
                bundle.description,
                bundle.version,
                now
            ],
        )?;
        conn.execute(
            "DELETE FROM test_template_bundle_items WHERE bundle_id = ?1",
            [bundle.id],
        )?;
        let mut item = conn.prepare(
            "INSERT OR IGNORE INTO test_template_bundle_items
                (bundle_id, template_id, origin_template_id, sort_order)
             VALUES (?1, ?2, ?2, ?3)",
        )?;
        for (index, template_id) in bundle.template_ids.iter().enumerate() {
            item.execute(rusqlite::params![bundle.id, template_id, index as i64])?;
        }
    }
    Ok(())
}
