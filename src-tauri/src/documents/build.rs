use std::collections::HashMap;

use crate::domain::enums::{
    EngagementStatus, FindingStatus, RetestStatus, Severity, TestCaseStatus,
};
use crate::domain::models::{
    Assumption, Contact, Engagement, Evidence, Finding, Risk, ScopeAsset, TestCase,
};

use super::model::{DocumentKind, ReportBlock, ReportDocument, ReportSection};

pub struct ReportSource<'a> {
    pub engagement: &'a Engagement,
    pub scope_assets: &'a [ScopeAsset],
    pub risks: &'a [Risk],
    pub assumptions: &'a [Assumption],
    pub contacts: &'a [Contact],
    pub test_cases: &'a [TestCase],
    pub findings: &'a [Finding],
    pub evidence: &'a [Evidence],
    pub generated_by: &'a str,
    pub generated_at: &'a str,
}

pub fn build_report(kind: DocumentKind, source: &ReportSource<'_>) -> ReportDocument {
    let title = format!("{} - {}", kind.label(), source.engagement.name);
    let subtitle = format!(
        "{} | {} to {}",
        if source.engagement.client_code.is_empty() {
            "No client code"
        } else {
            &source.engagement.client_code
        },
        date_or_dash(&source.engagement.start_date),
        date_or_dash(&source.engagement.end_date)
    );
    let metadata = metadata(source);
    let sections = match kind {
        DocumentKind::TestPlan => vec![
            overview_section(source),
            scope_section(source),
            risks_section(source),
            assumptions_section(source),
            contacts_section(source),
            methodology_section(),
            test_cases_section(source),
        ],
        DocumentKind::TestCaseTracker => {
            vec![test_progress_section(source), test_cases_section(source)]
        }
        DocumentKind::FindingsRegister => vec![
            severity_summary_section(source),
            findings_section(source),
            evidence_section(source),
        ],
        DocumentKind::ExecutiveSummary => vec![
            overview_section(source),
            test_progress_section(source),
            severity_summary_section(source),
            key_findings_section(source),
            assumptions_section(source),
            conclusion_section(source),
        ],
        DocumentKind::TechnicalReport => {
            let mut sections = vec![
                overview_section(source),
                scope_section(source),
                risks_section(source),
                assumptions_section(source),
                methodology_section(),
                test_progress_section(source),
                severity_summary_section(source),
                findings_section(source),
                evidence_section(source),
                test_cases_section(source),
            ];
            sections.extend(finding_detail_sections(source));
            sections
        }
    };

    ReportDocument {
        title,
        subtitle,
        metadata,
        sections,
    }
}

fn metadata(source: &ReportSource<'_>) -> Vec<(String, String)> {
    vec![
        (
            "Client code".into(),
            if source.engagement.client_code.is_empty() {
                "Not recorded".into()
            } else {
                source.engagement.client_code.clone()
            },
        ),
        (
            "Status".into(),
            engagement_status_label(source.engagement.status).into(),
        ),
        (
            "Test window".into(),
            format!(
                "{} to {}",
                date_or_dash(&source.engagement.start_date),
                date_or_dash(&source.engagement.end_date)
            ),
        ),
        (
            "Engagement version".into(),
            format!("v{}", source.engagement.version),
        ),
        ("Generated by".into(), source.generated_by.into()),
        ("Generated at".into(), source.generated_at.into()),
    ]
}

fn overview_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Engagement overview".into(),
        blocks: vec![
            ReportBlock::Paragraph(text_or(
                &source.engagement.application_summary,
                "No application summary recorded.",
            )),
            ReportBlock::Paragraph(format!(
                "Attack surface: {}",
                text_or(
                    &source.engagement.attack_surface,
                    "No attack surface recorded."
                )
            )),
        ],
    }
}

fn scope_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Scope and attack surface".into(),
        blocks: vec![table(
            &["Kind", "Asset", "Scope", "Notes"],
            source
                .scope_assets
                .iter()
                .map(|asset| {
                    vec![
                        asset.kind.replace('_', " "),
                        asset.value.clone(),
                        if asset.in_scope {
                            "In scope".into()
                        } else {
                            "Out of scope".into()
                        },
                        text_or(&asset.notes, "None"),
                    ]
                })
                .collect(),
            "No scope assets recorded.",
        )],
    }
}

fn risks_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Scoping risks".into(),
        blocks: vec![table(
            &["Risk", "Likelihood", "Impact", "Severity", "Description"],
            source
                .risks
                .iter()
                .map(|risk| {
                    vec![
                        risk.title.clone(),
                        risk.likelihood.to_string(),
                        risk.impact.to_string(),
                        severity_label(risk.severity).into(),
                        text_or(&risk.description, "None"),
                    ]
                })
                .collect(),
            "No risks recorded.",
        )],
    }
}

fn assumptions_section(source: &ReportSource<'_>) -> ReportSection {
    let items: Vec<String> = source
        .assumptions
        .iter()
        .map(|assumption| assumption.text.clone())
        .collect();
    ReportSection {
        heading: "Assumptions and limitations".into(),
        blocks: vec![if items.is_empty() {
            ReportBlock::Paragraph("No assumptions recorded.".into())
        } else {
            ReportBlock::Bullets(items)
        }],
    }
}

fn contacts_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Contacts".into(),
        blocks: vec![table(
            &["Name", "Role", "Email", "Phone"],
            source
                .contacts
                .iter()
                .map(|contact| {
                    vec![
                        contact.name.clone(),
                        text_or(&contact.role, "None"),
                        text_or(&contact.email, "None"),
                        text_or(&contact.phone, "None"),
                    ]
                })
                .collect(),
            "No contacts recorded.",
        )],
    }
}

fn methodology_section() -> ReportSection {
    ReportSection {
        heading: "Methodology".into(),
        blocks: vec![
            ReportBlock::Paragraph(
                "Testing followed the approved application security testing methodology: kickoff and scoping, mapping and information gathering, manual and tool-assisted testing, reporting, and project wrap-up."
                    .into(),
            ),
            ReportBlock::Paragraph(
                "Test cases were selected from reusable domain templates and customized to the engagement scope. Findings are recorded separately from test results, with severity derived from the approved Probability x Impact matrix."
                    .into(),
            ),
        ],
    }
}

fn test_cases_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Test case tracker".into(),
        blocks: vec![table(
            &["Test", "Category", "Status", "Result", "Assignee"],
            source
                .test_cases
                .iter()
                .map(|test_case| {
                    vec![
                        test_case.title.clone(),
                        text_or(&test_case.category, "Uncategorized"),
                        test_case_status_label(test_case.status).into(),
                        text_or(&test_case.result, "No result recorded"),
                        text_or(&test_case.assignee, "Unassigned"),
                    ]
                })
                .collect(),
            "No test cases recorded.",
        )],
    }
}

fn test_progress_section(source: &ReportSource<'_>) -> ReportSection {
    let mut not_started: usize = 0;
    let mut in_progress: usize = 0;
    let mut done: usize = 0;
    let mut blocked: usize = 0;
    let mut not_applicable: usize = 0;
    for test_case in source.test_cases {
        match test_case.status {
            TestCaseStatus::NotStarted => not_started += 1,
            TestCaseStatus::InProgress => in_progress += 1,
            TestCaseStatus::Done => done += 1,
            TestCaseStatus::Blocked => blocked += 1,
            TestCaseStatus::NotApplicable => not_applicable += 1,
        }
    }
    let total = source.test_cases.len();
    let applicable = total.saturating_sub(not_applicable);
    let completion = (done * 100).checked_div(applicable).unwrap_or(0);
    ReportSection {
        heading: "Testing progress".into(),
        blocks: vec![
            ReportBlock::Paragraph(format!(
                "{done} of {applicable} applicable tests completed ({completion}%). {total} tests recorded in total."
            )),
            ReportBlock::Table {
                headers: vec!["Status".into(), "Count".into()],
                rows: vec![
                    vec!["Not started".into(), not_started.to_string()],
                    vec!["In progress".into(), in_progress.to_string()],
                    vec!["Done".into(), done.to_string()],
                    vec!["Blocked".into(), blocked.to_string()],
                    vec!["Not applicable".into(), not_applicable.to_string()],
                ],
            },
        ],
    }
}

fn severity_summary_section(source: &ReportSource<'_>) -> ReportSection {
    let counts = severity_counts(source);
    ReportSection {
        heading: "Findings by severity".into(),
        blocks: vec![
            ReportBlock::Paragraph(format!(
                "{} findings recorded; {} remain open.",
                source.findings.len(),
                open_findings(source)
            )),
            ReportBlock::Table {
                headers: vec!["Severity".into(), "Count".into()],
                rows: vec![
                    vec!["Critical".into(), counts[4].to_string()],
                    vec!["High".into(), counts[3].to_string()],
                    vec!["Medium".into(), counts[2].to_string()],
                    vec!["Low".into(), counts[1].to_string()],
                    vec!["Informational".into(), counts[0].to_string()],
                ],
            },
        ],
    }
}

fn findings_section(source: &ReportSource<'_>) -> ReportSection {
    ReportSection {
        heading: "Findings register".into(),
        blocks: vec![table(
            &[
                "Code", "Title", "Severity", "Status", "Retest", "Owner", "OWASP", "CWE",
            ],
            source
                .findings
                .iter()
                .map(|finding| {
                    vec![
                        finding.code.clone(),
                        finding.title.clone(),
                        severity_label(finding.severity).into(),
                        finding_status_label(finding.status).into(),
                        retest_status_label(finding.retest_status).into(),
                        text_or(&finding.owner, "Unassigned"),
                        text_or(&finding.owasp, "None"),
                        text_or(&finding.cwe, "None"),
                    ]
                })
                .collect(),
            "No findings recorded.",
        )],
    }
}

fn key_findings_section(source: &ReportSource<'_>) -> ReportSection {
    let mut findings: Vec<&Finding> = source.findings.iter().collect();
    findings.sort_by_key(|finding| std::cmp::Reverse(severity_rank(finding.severity)));
    findings.truncate(10);
    ReportSection {
        heading: "Key findings".into(),
        blocks: vec![table(
            &["Code", "Title", "Severity", "Status", "Owner"],
            findings
                .into_iter()
                .map(|finding| {
                    vec![
                        finding.code.clone(),
                        finding.title.clone(),
                        severity_label(finding.severity).into(),
                        finding_status_label(finding.status).into(),
                        text_or(&finding.owner, "Unassigned"),
                    ]
                })
                .collect(),
            "No findings recorded.",
        )],
    }
}

fn evidence_section(source: &ReportSource<'_>) -> ReportSection {
    let test_cases: HashMap<&str, &str> = source
        .test_cases
        .iter()
        .map(|test_case| (test_case.id.as_str(), test_case.title.as_str()))
        .collect();
    let findings: HashMap<&str, &str> = source
        .findings
        .iter()
        .map(|finding| (finding.id.as_str(), finding.code.as_str()))
        .collect();
    ReportSection {
        heading: "Evidence references".into(),
        blocks: vec![table(
            &["File", "Caption", "Finding", "Test case", "Added"],
            source
                .evidence
                .iter()
                .map(|evidence| {
                    vec![
                        evidence.filename.clone(),
                        text_or(&evidence.caption, "None"),
                        evidence
                            .finding_id
                            .as_deref()
                            .and_then(|id| findings.get(id).copied())
                            .unwrap_or("None")
                            .to_string(),
                        evidence
                            .test_case_id
                            .as_deref()
                            .and_then(|id| test_cases.get(id).copied())
                            .unwrap_or("None")
                            .to_string(),
                        evidence.created_at.clone(),
                    ]
                })
                .collect(),
            "No evidence attached.",
        )],
    }
}

fn finding_detail_sections(source: &ReportSource<'_>) -> Vec<ReportSection> {
    source
        .findings
        .iter()
        .map(|finding| {
            let linked_evidence: Vec<Vec<String>> = source
                .evidence
                .iter()
                .filter(|evidence| evidence.finding_id.as_deref() == Some(finding.id.as_str()))
                .map(|evidence| {
                    vec![
                        evidence.filename.clone(),
                        text_or(&evidence.caption, "None"),
                    ]
                })
                .collect();
            let mut blocks = vec![
                ReportBlock::Table {
                    headers: vec![
                        "Severity".into(),
                        "Status".into(),
                        "Retest".into(),
                        "Owner".into(),
                        "OWASP".into(),
                        "CWE".into(),
                        "Probability".into(),
                        "Impact".into(),
                    ],
                    rows: vec![vec![
                        severity_label(finding.severity).into(),
                        finding_status_label(finding.status).into(),
                        retest_status_label(finding.retest_status).into(),
                        text_or(&finding.owner, "Unassigned"),
                        text_or(&finding.owasp, "None"),
                        text_or(&finding.cwe, "None"),
                        finding.probability.to_string(),
                        finding.impact_score.to_string(),
                    ]],
                },
                ReportBlock::Paragraph(format!(
                    "Description: {}",
                    text_or(&finding.description, "Not recorded.")
                )),
                ReportBlock::Paragraph(format!(
                    "Impact: {}",
                    text_or(&finding.impact, "Not recorded.")
                )),
                ReportBlock::Paragraph(format!(
                    "Remediation: {}",
                    text_or(&finding.remediation, "Not recorded.")
                )),
            ];
            if !linked_evidence.is_empty() {
                blocks.push(ReportBlock::Table {
                    headers: vec!["Evidence".into(), "Caption".into()],
                    rows: linked_evidence,
                });
            }
            ReportSection {
                heading: format!("Finding {} - {}", finding.code, finding.title),
                blocks,
            }
        })
        .collect()
}

fn conclusion_section(source: &ReportSource<'_>) -> ReportSection {
    let counts = severity_counts(source);
    let critical_high = counts[4] + counts[3];
    let text = if source.findings.is_empty() {
        "No findings were recorded during this engagement. Review the test tracker for executed coverage and any limitations documented in the assumptions.".to_string()
    } else if critical_high > 0 {
        format!(
            "The engagement recorded {} findings, including {} critical or high severity issues. Address the highest-risk findings first and schedule retesting after remediation.",
            source.findings.len(),
            critical_high
        )
    } else {
        format!(
            "The engagement recorded {} findings with no critical or high severity issues. Track remediation and retesting for the remaining items.",
            source.findings.len()
        )
    };
    ReportSection {
        heading: "Conclusion".into(),
        blocks: vec![ReportBlock::Paragraph(text)],
    }
}

fn table(headers: &[&str], rows: Vec<Vec<String>>, empty: &str) -> ReportBlock {
    if rows.is_empty() {
        return ReportBlock::Paragraph(empty.into());
    }
    ReportBlock::Table {
        headers: headers.iter().map(|header| (*header).to_string()).collect(),
        rows,
    }
}

fn severity_counts(source: &ReportSource<'_>) -> [usize; 5] {
    let mut counts = [0usize; 5];
    for finding in source.findings {
        counts[severity_rank(finding.severity)] += 1;
    }
    counts
}

fn open_findings(source: &ReportSource<'_>) -> usize {
    source
        .findings
        .iter()
        .filter(|finding| {
            matches!(
                finding.status,
                FindingStatus::Open | FindingStatus::InReview | FindingStatus::RetestPending
            )
        })
        .count()
}

fn severity_rank(severity: Severity) -> usize {
    match severity {
        Severity::Informational => 0,
        Severity::Low => 1,
        Severity::Medium => 2,
        Severity::High => 3,
        Severity::Critical => 4,
    }
}

fn severity_label(severity: Severity) -> &'static str {
    match severity {
        Severity::Informational => "Informational",
        Severity::Low => "Low",
        Severity::Medium => "Medium",
        Severity::High => "High",
        Severity::Critical => "Critical",
    }
}

fn engagement_status_label(status: EngagementStatus) -> &'static str {
    match status {
        EngagementStatus::Draft => "Draft",
        EngagementStatus::Active => "Active",
        EngagementStatus::InReview => "In review",
        EngagementStatus::Completed => "Completed",
        EngagementStatus::Archived => "Archived",
    }
}

fn test_case_status_label(status: TestCaseStatus) -> &'static str {
    match status {
        TestCaseStatus::NotStarted => "Not started",
        TestCaseStatus::InProgress => "In progress",
        TestCaseStatus::Done => "Done",
        TestCaseStatus::Blocked => "Blocked",
        TestCaseStatus::NotApplicable => "Not applicable",
    }
}

fn finding_status_label(status: FindingStatus) -> &'static str {
    match status {
        FindingStatus::Open => "Open",
        FindingStatus::InReview => "In review",
        FindingStatus::Remediated => "Remediated",
        FindingStatus::RetestPending => "Retest pending",
        FindingStatus::Closed => "Closed",
        FindingStatus::Accepted => "Accepted",
    }
}

fn retest_status_label(status: RetestStatus) -> &'static str {
    match status {
        RetestStatus::NotRequired => "Not required",
        RetestStatus::Pending => "Pending",
        RetestStatus::Passed => "Passed",
        RetestStatus::Failed => "Failed",
    }
}

fn date_or_dash(value: &str) -> String {
    if value.is_empty() {
        "-".into()
    } else {
        value.to_string()
    }
}

fn text_or(value: &str, fallback: &str) -> String {
    if value.trim().is_empty() {
        fallback.into()
    } else {
        value.trim().to_string()
    }
}
